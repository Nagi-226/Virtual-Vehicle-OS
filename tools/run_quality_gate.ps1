param(
    [string]$BuildDir = "build",
    [string]$BenchmarkOutput = "",
    [string]$BaselineFile = "tools/benchmark_baseline.json",
    [string]$ReportPath = "",
    [string]$SourceRoot = ".",
    [double]$MinThroughput = 500.0,
    [double]$MaxErrorRate = 0.05,
    [double]$MaxP99LatencyMs = 200.0,
    [double]$MinSoakSamples = 50.0,
    [switch]$RunCtest = $true,
    [switch]$EnableSTM32F429Check = $false,
    [string]$STM32BuildDir = "build-stm32f429"
)

# NOTE: this file is intentionally ASCII-only. Windows PowerShell 5.1 reads .ps1
# files without a BOM as ANSI; UTF-8 multibyte characters then swallow the next
# byte and break tokenization (leading to bogus "unexpected token }" parse
# errors). Keep any non-ASCII text out of this script.

$ErrorActionPreference = "Stop"

# ============================================================================
# Hard assertions for gate truthfulness (task T04)
#
# Background (finding A2): build/Testing contained 15 ctest records spanning
# 2026-03-15 .. 2026-07-21, each 142 bytes with only "Start testing" /
# "End testing" and an empty <TestList/> in Test.xml. In other words zero tests
# were executed, yet the gate reported pass, because the script only ran a
# hand-picked list of test names and never verified how many tests actually ran.
#
# The assertions below make that situation necessarily red:
#   1) ctest -N registered count is compared both ways against the declaration
#      manifest generated by CMake (vvos_declared_tests.txt);
#   2) every registered test must have an existing executable on disk, so ctest
#      cannot silently report "Not Run";
#   3) the number of executed tests must equal the number registered, and zero
#      executed tests is always a failure.
# ============================================================================

$requiredTests = @(
    "interconnect_fault_injection_test",
    "interconnect_config_reload_test",
    "interconnect_protocol_adapter_test"
)

$advisoryTests = @(
    "interconnect_tcp_loopback_test",
    "interconnect_metrics_delta_test"
)

# Reads the manifest CMake writes at configure time. It is already evaluated
# against the real platform conditionals, so the comparison is exact.
function Read-DeclaredTests {
    param([string]$Directory)

    $manifest = Join-Path $Directory "vvos_declared_tests.txt"
    if (-not (Test-Path $manifest)) {
        return $null
    }

    $names = @()
    foreach ($line in (Get-Content $manifest)) {
        $trimmed = $line.Trim()
        if ($trimmed -ne "") {
            $names += $trimmed
        }
    }
    return ,$names
}

# Registered test names, parsed from `ctest -N` plain text.
function Read-RegisteredTests {
    param([string]$Directory)

    $prev = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    $raw = (& ctest --test-dir $Directory -N 2>&1 | Out-String)
    $ErrorActionPreference = $prev

    $names = @()
    foreach ($m in [regex]::Matches($raw, "(?m)^\s*Test\s+#\d+:\s*(\S+)\s*$")) {
        $names += $m.Groups[1].Value
    }
    return ,$names
}

# Detects registered tests whose executable cannot be resolved on disk.
# `ctest --show-only=json-v1` does not expose the command for these tests in all
# ctest versions, so this asks ctest itself for its verbose test list, where a
# unresolvable executable shows up as "Could not find executable <path>" and an
# empty "Test command:" field. Returns the offending paths (possibly empty).
function Read-MissingTestBinaries {
    param([string]$Directory)

    $missing = @()
    $prev = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    $raw = (& ctest --test-dir $Directory -N -V 2>&1 | Out-String)
    $ErrorActionPreference = $prev

    foreach ($m in [regex]::Matches($raw, "(?m)^Could not find executable\s+(\S*)")) {
        $missing += $m.Groups[1].Value
    }
    if ($missing.Count -eq 0) {
        return
    }
    return $missing
}

# Executed test count, taken from the ctest summary line
# "100% tests passed, 0 tests failed out of 19".
function Read-ExecutedTestCount {
    param([string]$CtestOutput)

    $m = [regex]::Match($CtestOutput, "out of\s+(\d+)")
    if ($m.Success) {
        return [int]$m.Groups[1].Value
    }

    $perTest = [regex]::Matches($CtestOutput, "(?m)^\s*\d+/\d+\s+Test\s+#\d+:")
    return $perTest.Count
}

# Failed test names, taken from the trailing "The following tests FAILED:" block.
# Those entries are the only lines shaped "<index> - <name>" in ctest output;
# every per-test progress line looks like "  3/19 Test #3: ...", so a global
# multiline match is unambiguous and avoids string-splitting pitfalls.
function Read-FailedTestNames {
    param([string]$CtestOutput)

    $failed = @()
    foreach ($m in [regex]::Matches($CtestOutput, "(?m)^\s*\d+\s+-\s+(\S+)")) {
        $failed += $m.Groups[1].Value
    }
    if ($failed.Count -eq 0) {
        return
    }
    # Emit item by item so the caller's @(...) sees one element per test name.
    # Returning ,$failed here would hand back a single array object and later
    # interpolation would flatten all names into one string.
    return $failed
}

function Parse-Throughput {
    param([string]$Content)

    if ($Content -match '"throughput_msg_per_sec"\s*:\s*([0-9]+\.?[0-9]*)') {
        return [double]$matches[1]
    }
    if ($Content -match 'throughput_msg_per_sec:\s*([0-9]+\.?[0-9]*)') {
        return [double]$matches[1]
    }
    return 0.0
}

function Parse-ErrorRate {
    param([string]$Content)

    if ($Content -match '"error_rate"\s*:\s*([0-9]+\.?[0-9]*)') {
        return [double]$matches[1]
    }
    if ($Content -match 'error_rate:\s*([0-9]+\.?[0-9]*)') {
        return [double]$matches[1]
    }
    return 0.0
}

function Parse-P99 {
    param([string]$Content)

    if ($Content -match '"latency_p99_ms"\s*:\s*([0-9]+\.?[0-9]*)') {
        return [double]$matches[1]
    }
    if ($Content -match 'latency_p99_ms:\s*([0-9]+\.?[0-9]*)') {
        return [double]$matches[1]
    }
    return 0.0
}

function Parse-SoakSamples {
    param([string]$Content)

    $v2r = 0.0
    $r2v = 0.0
    if ($Content -match '"v2r_received"\s*:\s*([0-9]+\.?[0-9]*)') {
        $v2r = [double]$matches[1]
    }
    if ($Content -match '"r2v_received"\s*:\s*([0-9]+\.?[0-9]*)') {
        $r2v = [double]$matches[1]
    }
    return ($v2r + $r2v)
}

function Parse-FaultAssertion {
    param([string]$Content)

    if ($Content -match '"fault_assertion_pass"\s*:\s*(true|false)') {
        return $matches[1] -eq 'true'
    }
    if ($Content -match 'fault_assertion_pass:\s*(true|false)') {
        return $matches[1] -eq 'true'
    }
    return $false
}

function Load-Baseline {
    param([string]$Path)

    if (-not (Test-Path $Path)) {
        return @{ throughput = 0.0 }
    }

    try {
        return (Get-Content $Path -Raw | ConvertFrom-Json)
    } catch {
        return @{ throughput = 0.0 }
    }
}

# Static guard for TN-01 (docs/toolchain-notes.md): on this toolchain a
# thread_local object with a non-trivial destructor crashes the process with
# 0xC0000374 when the thread exits. Only trivially-destructible types are
# allowed (bool / integers / floats / char / size_t / std::intN_t / std::uintN_t
# / fixed char arrays).
#
# Heuristic, single-line only: comment-only lines are skipped, multi-line
# declarations may slip through, and it is NOT a substitute for code review.
function Find-ForbiddenThreadLocals {
    param([string]$SourceRoot)

    $allowed = '^\s*(?:static\s+)?thread_local\s+(?:bool|char|short|int|long|unsigned|signed|float|double|std::size_t|std::int\d+_t|std::uint\d+_t|const\s+char)\b'
    $hits = @()

    foreach ($dir in @("src", "tests", "demo")) {
        $dirPath = Join-Path $SourceRoot $dir
        if (-not (Test-Path $dirPath)) {
            continue
        }
        foreach ($file in (Get-ChildItem -Path $dirPath -Recurse -File -Include *.cpp, *.hpp, *.h, *.c)) {
            $lineNo = 0
            foreach ($line in (Get-Content $file.FullName)) {
                $lineNo++
                if ($line -notmatch 'thread_local') {
                    continue
                }
                $trimmed = $line.TrimStart()
                if ($trimmed.StartsWith("//") -or $trimmed.StartsWith("*") -or $trimmed.StartsWith("/*")) {
                    continue
                }
                if ($line -notmatch $allowed) {
                    $hits += ("{0}:{1}" -f $file.FullName, $lineNo)
                }
            }
        }
    }

    if ($hits.Count -eq 0) {
        return
    }
    return $hits
}

Write-Host "[quality-gate] start"

$blockReasons = @()
$declaredCount = 0
$registeredCount = 0
$executedCount = 0
$testCountFromCtestList = 0
$failedTestNames = @()
$advisoryFailed = @()

if ($RunCtest -and -not (Test-Path $BuildDir)) {
    Write-Host "[quality-gate] build dir not found: $BuildDir"
    exit 1
}

# ---------------------------------------------------------------------------
# 1) Declaration manifest versus ctest registration: count and name comparison
# ---------------------------------------------------------------------------
$declaredTests = @()
$registeredTests = @()

if ($RunCtest) {
    $declared = Read-DeclaredTests -Directory $BuildDir
    if ($null -eq $declared) {
        $blockReasons += "declared_test_manifest_missing"
        Write-Host "[quality-gate][assert] vvos_declared_tests.txt missing: cannot prove declaration/registration agreement"
    } else {
        $declaredTests = @($declared)
        $declaredCount = $declaredTests.Count
    }

    $registered = Read-RegisteredTests -Directory $BuildDir
    $registeredTests = @($registered)
    $registeredCount = $registeredTests.Count

    Write-Host "[quality-gate][assert] declared=$declaredCount registered=$registeredCount"

    if ($declaredCount -eq 0) {
        $blockReasons += "declared_tests_zero"
    }
    if ($registeredCount -eq 0) {
        $blockReasons += "registered_tests_zero"
    }
    if (($declaredCount -ne $registeredCount) -and ($declaredCount -gt 0) -and ($registeredCount -gt 0)) {
        $blockReasons += "test_count_mismatch_declared_${declaredCount}_registered_${registeredCount}"
        Write-Host "[quality-gate][assert] declared/registered count mismatch: $declaredCount vs $registeredCount"
    }

    foreach ($name in $declaredTests) {
        if ($registeredTests -notcontains $name) {
            $blockReasons += "test_declared_but_not_registered:$name"
        }
    }
    foreach ($name in $registeredTests) {
        if ($declaredTests -notcontains $name) {
            $blockReasons += "test_registered_but_not_declared:$name"
        }
    }

    # -----------------------------------------------------------------------
    # 2) Every registered test must have a resolvable executable on disk.
    #    Lesson from A2: build/ held zero object files and nobody noticed,
    #    because nothing ever verified what was actually run.
    # -----------------------------------------------------------------------
    $missingBinaries = Read-MissingTestBinaries -Directory $BuildDir
    if ($null -ne $missingBinaries) {
        foreach ($path in @($missingBinaries)) {
            $blockReasons += "test_binary_missing:$path"
            Write-Host "[quality-gate][assert] test executable missing: $path"
        }
    }
} else {
    # No ctest run means no evidence at all; such a "pass" has the same nature
    # as the A2 false green light.
    $blockReasons += "ctest_skipped_no_test_evidence"
}

# ---------------------------------------------------------------------------
# 3) Run the whole suite once and require executed == registered, executed > 0
#    Running a hand-picked subset was the root cause of the false green light.
# ---------------------------------------------------------------------------
$ctestExit = 0
if ($RunCtest) {
    $prev = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    $ctestOutput = (& ctest --test-dir $BuildDir --output-on-failure 2>&1 | Out-String)
    $ctestExit = $LASTEXITCODE
    $ErrorActionPreference = $prev

    Write-Host $ctestOutput

    $executedCount = Read-ExecutedTestCount -CtestOutput $ctestOutput
    $failedProbe = Read-FailedTestNames -CtestOutput $ctestOutput
    $failedTestNames = @()
    if ($null -ne $failedProbe) {
        $failedTestNames = @($failedProbe)
    }

    Write-Host "[quality-gate][assert] executed=$executedCount registered=$registeredCount"

    if ($executedCount -eq 0) {
        $blockReasons += "tests_executed_zero"
    }
    if (($registeredCount -gt 0) -and ($executedCount -ne $registeredCount)) {
        $blockReasons += "tests_executed_mismatch_expected_${registeredCount}_actual_${executedCount}"
    }
    if ($ctestExit -ne 0) {
        $blockReasons += "ctest_suite_failed"
    }

    foreach ($name in $failedTestNames) {
        if ($requiredTests -contains $name) {
            $blockReasons += "required_tests_failed:$name"
        } else {
            $blockReasons += "test_failed:$name"
        }
    }

    # The legacy "advisory" list is kept as an attribution label only; it no
    # longer allows silent failure. A red test always blocks the gate.
    foreach ($name in $failedTestNames) {
        if ($advisoryTests -contains $name) {
            $advisoryFailed += $name
        }
    }
    if ($advisoryFailed.Count -gt 0) {
        Write-Host "[quality-gate][advisory] failed=$($advisoryFailed -join ',')"
    }
}

# ---------------------------------------------------------------------------
# 4) Source-level static check: forbid non-trivially-destructible thread_local
#    (TN-01 in docs/toolchain-notes.md). This one is independent of ctest, so it
#    runs even with -RunCtest:$false.
# ---------------------------------------------------------------------------
$forbiddenTls = Find-ForbiddenThreadLocals -SourceRoot $SourceRoot
if ($null -ne $forbiddenTls) {
    foreach ($hit in @($forbiddenTls)) {
        $blockReasons += "thread_local_nontrivial_forbidden:$hit"
        Write-Host "[quality-gate][assert] non-trivially-destructible thread_local: $hit (see docs/toolchain-notes.md TN-01)"
    }
}

$throughput = 0.0
$errorRate = 0.0
$p99 = 0.0
$soakSamples = 0.0
$faultAssertPass = $true
$benchPass = $true
$soakPass = $true
$regressWarn = $false
$baseline = Load-Baseline -Path $BaselineFile
$baselineThroughput = [double]$baseline.throughput

if ($BenchmarkOutput -and (Test-Path $BenchmarkOutput)) {
    $content = Get-Content $BenchmarkOutput -Raw
    $throughput = Parse-Throughput -Content $content
    $errorRate = Parse-ErrorRate -Content $content
    $p99 = Parse-P99 -Content $content
    $soakSamples = Parse-SoakSamples -Content $content

    $benchPass = $throughput -ge $MinThroughput
    $soakPass = ($errorRate -le $MaxErrorRate) -and ($p99 -le $MaxP99LatencyMs) -and ($soakSamples -ge $MinSoakSamples)
    $faultAssertPass = Parse-FaultAssertion -Content $content

    if ($baselineThroughput -gt 0 -and $throughput -lt ($baselineThroughput * 0.95)) {
        $regressWarn = $true
    }

    Write-Host "[quality-gate][benchmark] throughput=$throughput min=$MinThroughput baseline=$baselineThroughput"
    Write-Host "[quality-gate][soak] error_rate=$errorRate max=$MaxErrorRate p99=$p99 max_p99=$MaxP99LatencyMs samples=$soakSamples min_samples=$MinSoakSamples"
} else {
    Write-Host "[quality-gate][benchmark] output not provided, skip hard gate"
}

if ($EnableSTM32F429Check) {
    $stm32Elf = Join-Path $STM32BuildDir "stm32f429_min_fw"
    $stm32Hex = Join-Path $STM32BuildDir "stm32f429_min_fw.hex"
    $stm32Bin = Join-Path $STM32BuildDir "stm32f429_min_fw.bin"

    $stm32ArtifactsOk = (Test-Path $stm32Elf) -and (Test-Path $stm32Hex) -and (Test-Path $stm32Bin)
    if (-not $stm32ArtifactsOk) {
        $blockReasons += "stm32f429_artifacts_missing"
    }

    $prevStm32 = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    Write-Host "[quality-gate][platform-required] running f429_bridge_diag_adapter_test"
    & ctest --test-dir $BuildDir -R "^f429_bridge_diag_adapter_test$" --output-on-failure
    if ($LASTEXITCODE -ne 0) {
        $blockReasons += "f429_diag_bridge_test_failed"
        Write-Host "[quality-gate][platform-required] fail: f429_bridge_diag_adapter_test"
    }
    $ErrorActionPreference = $prevStm32
}

if (-not $benchPass) {
    $blockReasons += "benchmark_throughput_below_threshold"
}
if (-not $soakPass) {
    if ($soakSamples -lt $MinSoakSamples) {
        $blockReasons += "soak_samples_too_low"
    } else {
        $blockReasons += "soak_or_fault_threshold_violation"
    }
}
if (-not $faultAssertPass) {
    $blockReasons += "fault_assertion_failed"
}

if ($blockReasons.Count -eq 0) {
    Write-Host "[quality-gate] release_gate=pass"
} else {
    Write-Host "[quality-gate] release_gate=fail"
}

if ($regressWarn) {
    Write-Host "[quality-gate] performance_regression_warning=true"
}
if ($blockReasons.Count -gt 0) {
    Write-Host "[quality-gate] block_reasons=$($blockReasons -join ',')"
}

$releaseGate = if ($blockReasons.Count -eq 0) { 'pass' } else { 'fail' }
$ciReport = [PSCustomObject]@{
    throughput = $throughput
    error_rate = $errorRate
    p99_ms = $p99
    tests_declared = $declaredCount
    tests_registered = $registeredCount
    tests_executed = $executedCount
    tests_failed = $failedTestNames.Count
    fault_assertion = $faultAssertPass
    release_gate = $releaseGate
    block_reasons = ($blockReasons -join '|')
}
Write-Host ("[quality-gate] ci_report=" + ($ciReport | ConvertTo-Json -Compress))

# Machine-readable handoff for release_gate_v09.ps1. Console text alone is not a
# reliable channel between two nested powershell.exe processes on PowerShell 5.1,
# and the release gate must not be able to pass by failing to read this gate's
# verdict.
if ($ReportPath -ne "") {
    ($ciReport | ConvertTo-Json -Compress) | Set-Content -Path $ReportPath -Encoding UTF8
}

if ($blockReasons.Count -eq 0) {
    exit 0
}
exit 1
